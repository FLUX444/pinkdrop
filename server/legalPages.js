const ALLOWED_TAGS = new Set(['section', 'h2', 'p', 'ul', 'li', 'a', 'br', 'strong', 'em']);

function escapeHtml(value) {
  return String(value ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function sanitizeLegalHtml(html) {
  const source = String(html ?? '').trim();
  if (!source) return '';

  return source.replace(/<\/?([a-z][a-z0-9]*)\b[^>]*>/gi, (match, tagName) => {
    const tag = String(tagName).toLowerCase();
    if (!ALLOWED_TAGS.has(tag)) return '';
    if (match.startsWith('</')) return `</${tag}>`;

    if (tag === 'a') {
      const hrefMatch = match.match(/\shref\s*=\s*("([^"]*)"|'([^']*)')/i);
      const href = hrefMatch?.[2] ?? hrefMatch?.[3] ?? '';
      if (!/^(https?:\/\/|mailto:)/i.test(href)) return '<a>';
      return `<a href="${escapeHtml(href)}">`;
    }

    return `<${tag}>`;
  });
}

export function legalRowToJson(row) {
  if (!row) return null;
  return {
    slug: row.slug,
    tag: row.tag,
    title: row.title,
    subtitle: row.subtitle,
    contentHtml: row.content_html,
    updatedAt: row.updated_at,
  };
}
